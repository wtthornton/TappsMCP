"""Tests for scripts/gen_sprint_board.py — the SPRINT_BOARD.md generator.

docs/SPRINT_BOARD.md is generated from Linear, not hand-maintained (the
prior hand-maintained docs/TAPPS_BACKLOG_PLAN.md drifted for the same
reason). These tests cover the render/grouping/freshness logic directly;
scripts/gen-sprint-board.py is a thin CLI shim over this module.
"""

from __future__ import annotations

import importlib
import json
import sys
from datetime import date, timedelta
from pathlib import Path
from typing import TYPE_CHECKING

import pytest

if TYPE_CHECKING:
    from types import ModuleType

REPO_ROOT = Path(__file__).resolve().parents[4]
SCRIPTS_DIR = REPO_ROOT / "scripts"


@pytest.fixture
def gsb() -> ModuleType:
    """Import scripts/gen_sprint_board.py — scripts/ is not an installed package."""
    if str(SCRIPTS_DIR) not in sys.path:
        sys.path.insert(0, str(SCRIPTS_DIR))
    return importlib.reload(importlib.import_module("gen_sprint_board"))


def _raw_issue(
    issue_id: str,
    priority: str,
    *,
    status: str = "Backlog",
    parent_id: str | None = None,
    url: str | None = None,
) -> dict[str, object]:
    return {
        "id": issue_id,
        "title": f"Title for {issue_id}",
        "priority": {"name": priority},
        "status": status,
        "statusType": status.lower(),
        "parentId": parent_id,
        "url": url or f"https://linear.app/example/issue/{issue_id}",
    }


class TestIssueFromDict:
    def test_from_dict_maps_priority_name(self, gsb: ModuleType) -> None:
        issue = gsb.Issue.from_dict(_raw_issue("TAP-1", "High"))
        assert issue.priority == "High"
        assert issue.id == "TAP-1"

    def test_from_dict_defaults_missing_priority(self, gsb: ModuleType) -> None:
        raw = _raw_issue("TAP-2", "High")
        raw["priority"] = None
        issue = gsb.Issue.from_dict(raw)
        assert issue.priority == "No priority"

    def test_from_dict_missing_parent_id_is_none(self, gsb: ModuleType) -> None:
        raw = _raw_issue("TAP-3", "Low")
        del raw["parentId"]
        issue = gsb.Issue.from_dict(raw)
        assert issue.parent_id is None


